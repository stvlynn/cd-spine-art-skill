import { isTheme } from '@repo/spine'
import { Ajv } from 'ajv'
import * as icons from 'simple-icons'
import schema from '../../catalog/presets.schema.json' with { type: 'json' }

interface Catalog {
  presets: {
    slug: string
    group: 'ai' | 'stack'
    theme: string
    icon?: string
    title?: string
    paint?: 'paper' | 'accent'
    aliases?: string[]
  }[]
}

const ajv = new Ajv({ allErrors: true })
const validate = ajv.compile<Catalog>(schema)

// The full package is used only by this build script. Generated code imports
// individual exports so the Worker's bundler can remove all unused icons.
const iconExports = new Map(Object.entries(icons).map(([name, icon]) => [icon.slug, name]))

function quote(value: string): string {
  const escaped = JSON.stringify(value)
    .slice(1, -1)
    .replaceAll('\\"', '"')
    .replaceAll("'", "\\'")
    .replaceAll('\u2028', '\\u2028')
    .replaceAll('\u2029', '\\u2029')
  return `'${escaped}'`
}

/** Validate the source catalog and emit a deterministic, statically imported registry. */
export function generatePresets(source: unknown): string {
  if (!validate(source)) {
    throw new Error(
      `Invalid preset catalog: ${ajv.errorsText(validate.errors, { separator: '\n' })}`,
    )
  }

  const names = new Set<string>()
  const imports = new Set<string>()
  const entries: string[] = []
  const aliases: string[] = []

  // Reserve canonical names first, including names declared after an alias.
  for (const { slug } of source.presets) {
    if (names.has(slug)) throw new Error(`Duplicate preset slug: ${slug}`)
    names.add(slug)
  }

  for (const entry of source.presets) {
    const { slug, group, theme, title, paint } = entry
    if (!isTheme(theme)) throw new Error(`Preset ${slug}: unknown theme ${theme}`)
    const iconSlug = entry.icon ?? slug
    const icon = iconExports.get(iconSlug)
    if (!icon) throw new Error(`Preset ${slug}: unknown Simple Icons slug ${iconSlug}`)
    imports.add(icon)

    for (const alias of entry.aliases ?? []) {
      if (names.has(alias))
        throw new Error(`Preset ${slug}: alias ${alias} conflicts with another name`)
      names.add(alias)
      aliases.push(`  [${quote(alias)}, ${quote(slug)}],`)
    }

    entries.push(
      [
        '  {',
        `    slug: ${quote(slug)},`,
        `    title: ${title === undefined ? `${icon}.title` : quote(title)},`,
        `    group: ${quote(group)},`,
        `    theme: ${quote(theme)},`,
        `    icon: ${icon},`,
        ...(paint === undefined ? [] : [`    paint: ${quote(paint)},`]),
        '  },',
      ].join('\n'),
    )
  }

  return [
    '// Generated by pnpm presets from catalog/presets.json. Do not edit.',
    'import {',
    ...[...imports].sort().map((name) => `  ${name},`),
    "} from 'simple-icons'",
    "import type { Preset } from './presets.ts'",
    '',
    'export const presets: Preset[] = [',
    ...entries,
    ']',
    '',
    'export const aliases: [string, string][] = [',
    ...aliases,
    ']',
    '',
  ].join('\n')
}
